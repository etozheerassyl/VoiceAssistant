#ifndef UI_THEME_H
#define UI_THEME_H

#include <Arduino.h>

// ============================================================================
// Разрешение дисплея ILI9341 в горизонтальной ориентации (setRotation(1))
// ============================================================================
#define SCREEN_WIDTH   320
#define SCREEN_HEIGHT  240

// ============================================================================
// Цветовая палитра премиального голосового помощника (16-битный RGB565)
// Глубокий черный фон, благородное золото, теплый бежевый и мягкие акценты
// ============================================================================
#define COLOR_BG            0x0000 // Абсолютный черный фон для глубокого контраста
#define COLOR_CARD_BG       0x0842 // Темный благородный графит для плашек и карточек
#define COLOR_CARD_BORDER   0x2124 // Сдержанный контур карточек
#define COLOR_CARD_HIGHLIGHT 0x31A6 // Легкий акцент границы при фокусе

#define COLOR_GOLD          0xFEA0 // Золотой акцент (основной фирменный цвет)
#define COLOR_GOLD_LIGHT    0xFFF2 // Светлое сияющее золото (хайлайты и пики эквалайзера)
#define COLOR_GOLD_MID      0xC580 // Насыщенное янтарное золото (средний уровень эквалайзера)
#define COLOR_GOLD_DARK     0x8B20 // Приглушенное темное золото для орнаментов и низа шкалы
#define COLOR_BEIGE         0xF73B // Теплый бежевый цвет для подписей и дат
#define COLOR_TEXT_WHITE    0xFFFF // Чистый белый для главного текста и цифр
#define COLOR_TEXT_MUTED    0x8410 // Приглушенный серый для вторичных подписей

// Цвета индикации состояний
#define COLOR_STATUS_READY  0x2FA6 // Изумрудно-зеленый (Готов)
#define COLOR_STATUS_LISTEN 0x2E7F // Бирюзово-голубой (Слушаю)
#define COLOR_STATUS_THINK  0xFDA0 // Янтарно-оранжевый (Обработка)
#define COLOR_STATUS_SPEAK  0xFEA0 // Золотистый (Ответ помощника)

// Цвета погоды
#define COLOR_SUN_GOLD      0xFEE0 // Солнечный золотой
#define COLOR_CLOUD_WHITE   0xCE59 // Мягкий облачный цвет

// Перечисление экранов системы
enum ScreenID {
  SCREEN_HOME = 0,      // Главный экран (часы, дата, погода, статус)
  SCREEN_MUSIC = 1,     // Музыкальный экран (эквалайзер, трек, плеер)
  SCREEN_VIDEO = 2,     // Экран видео / YouTube (плеер, прогресс, статус)
  SCREEN_ASSISTANT = 3, // Экран ассистента (состояния, анимация ядра)
  SCREEN_COUNT = 4
};

// Перечисление состояний голосового помощника
enum AssistantState {
  STATE_READY = 0,     // Готов к приему команды
  STATE_LISTENING = 1, // Запись речи пользователя
  STATE_THINKING = 2,  // Обработка запроса
  STATE_SPEAKING = 3   // Озвучивание ответа
};

#endif // UI_THEME_H
